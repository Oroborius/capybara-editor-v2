"""Names for the rows of game tables that store no name of their own in the compiled .bin files (skills without a
skilldesc, states without a buff icon, missiles, overlays, monsters).

The naming chain follows D2-Development-Kit (MIT), d2bt/binfmt/bin2txt.py NAME_SOURCES / USED_SOURCES: the row's
vanilla 1.13c key when its fingerprint columns still match vanilla (mxl_vanilla_keys.json, generated by
tools/gen_vanilla_keys.py from the kit's data/vanilla_keys.json), else a name derived from the rows it links to
or that link to it ('<user>: <role>'), else a short description of the row itself. Field offsets from the kit's
layouts/mxl/<table>.json (Median XL 2.14.6).

Every function takes the host's mxl_data.Data (`_rows(table)`, `s(string id)`, `skill_names`) and caches on it.
"""
import json
import os
import re
import struct

BUFFALO = 'POLAR BUFFALO'
NONE16 = (0, 0xFFFF)

# skills.bin
SK_CLASS, SK_SRVST, SK_SRVDO = 12, 44, 46
SK_SRVMIS = (70, 72, 74, 76)
SK_CLTMIS = (232, 234, 236, 238, 240)
SK_AURASTATE, SK_AURATARGET, SK_PASSIVESTATE = 128, 130, 148
SK_STATES = (554, 556, 558)
SK_SUMMON = 188
SK_SUMSKILL = (196, 198, 200, 202, 204)
SK_REQSKILL = (382, 384, 386)
# states.bin
ST_OVERLAY1, ST_CASTOVERLAY, ST_STAT, ST_SKILL, ST_MISSILE = 2, 10, 24, 56, 58
# missiles.bin
MI_CELFILE, MI_SKILL = 312, 404
# monstats.bin
MO_NAMESTR, MO_SKILLS = 6, tuple(range(368, 384, 2))
# weapons / armor / misc: state, cstate1, cstate2
IT_STATES = (152, 154, 156)
CLASS_NAMES = ('Amazon', 'Sorceress', 'Necromancer', 'Paladin', 'Barbarian', 'Druid', 'Assassin')


def _vanilla():
    global _VAN
    try:
        return _VAN
    except NameError:
        pass
    try:
        with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'mxl_vanilla_keys.json')) as fh:
            _VAN = json.load(fh)
    except (OSError, ValueError):
        _VAN = {}
    return _VAN


def _cache(data):
    c = data.__dict__.get('_rn_cache')
    if c is None:
        c = data.__dict__['_rn_cache'] = {}
    return c


def rows(data, table):
    c = _cache(data)
    key = 'rows:' + table
    if key not in c:
        try:
            c[key] = data._rows(table)
        except Exception:
            c[key] = []
    return c[key]


def _u16(r, off):
    return struct.unpack_from('<H', r, off)[0] if off + 2 <= len(r) else 0


def _cstr(r, off, n=64):
    return r[off:off + n].split(b'\0', 1)[0].decode('latin-1').strip()


def _ok(n):
    return bool(n) and BUFFALO not in n.upper()


def vanilla_names(data, table):
    """{row: vanilla key} for the rows whose fingerprint columns still match vanilla (at least 3 of 4) and whose
    key is unique (D2-Development-Kit, MIT: Context._vanilla_row_names)."""
    c = _cache(data)
    key = 'van:' + table
    if key in c:
        return c[key]
    res = {}
    van = _vanilla().get(table)
    if van:
        vnames, seen = [], set()
        for vr, nm in enumerate(van['names']):
            k = nm[:31].lower()
            if k not in seen:
                seen.add(k)
                vnames.append((nm, vr))
        first = {}
        for r, row in enumerate(rows(data, table)):
            first.setdefault(_u16(row, 0), r)
        used = set()
        for idx, r in sorted(first.items()):
            if idx >= len(vnames):
                continue
            nm, vr = vnames[idx]
            if not nm or re.match(r'^[a-z]{2}\d+$', nm) or nm[:31].lower() in used:
                continue
            row = rows(data, table)[r]
            tot = eq = 0
            for off, fmt, vals in van['fingerprint']:
                if vr < len(vals) and off + struct.calcsize(fmt) <= len(row) and isinstance(vals[vr], int):
                    tot += 1
                    eq += struct.unpack_from('<' + fmt, row, off)[0] == vals[vr]
            if tot and eq * 4 < tot * 3:
                continue
            res[r] = nm
            used.add(nm[:31].lower())
    c[key] = res
    return res


def _refs(data, table, offs):
    """{value: first row of table whose u16 at one of offs is that value} (first column first)."""
    c = _cache(data)
    key = ('ref', table, offs)
    if key not in c:
        m = {}
        for off in offs:
            for i, r in enumerate(rows(data, table)):
                v = _u16(r, off)
                if v not in NONE16:
                    m.setdefault(v, i)
        c[key] = m
    return c[key]


def skill_shown(data, sk):
    n = (getattr(data, 'skill_names', None) or {}).get(sk)
    return n if _ok(n) else None


def skill_base(data, sk):
    """A skill's display name, else its vanilla key (no derived names: used inside other rows' names)."""
    return skill_shown(data, sk) or vanilla_names(data, 'skills').get(sk)


def overlay_name(data, o):
    rs = rows(data, 'overlay')
    if not 0 < o < len(rs):
        return None
    n = vanilla_names(data, 'overlay').get(o) or _cstr(rs[o], 2)
    return n if n and n.lower() != 'null' else None


def missile_name(data, m, depth=0):
    rs = rows(data, 'missiles')
    if not 0 <= m < len(rs):
        return None
    n = vanilla_names(data, 'missiles').get(m)
    if n:
        return n
    cel = _cstr(rs[m], MI_CELFILE)
    if cel and cel.lower() != 'null':
        return cel
    sk = _u16(rs[m], MI_SKILL)
    if sk not in NONE16 and depth == 0:
        return skill_base(data, sk)
    return None


def monster_name(data, mid):
    rs = rows(data, 'monstats')
    if not 0 <= mid < len(rs):
        return None
    try:
        n = (data.s(_u16(rs[mid], MO_NAMESTR)) or '').replace('\n', ' ').strip()
    except Exception:
        n = ''
    if _ok(n) and not re.match(r'^(dummy|unused)', n, re.I):
        return n
    return vanilla_names(data, 'monstats').get(mid)


def _stat_name(data, sid):
    try:
        import mxl_statnames
        return mxl_statnames._short_stat(data, sid) or None
    except Exception:
        return None


def skill_derived(data, sk):
    """Name of a skill without a display name: vanilla key, or derived ('Frost Nova: aura'). None if nothing."""
    rs = rows(data, 'skills')
    if not 0 <= sk < len(rs):
        return None
    van = vanilla_names(data, 'skills').get(sk)
    if van:
        return van
    r = rs[sk]
    # NAME_SOURCES derived: monster that uses it, its missiles, a missile / state that names it
    mon = _refs(data, 'monstats', MO_SKILLS).get(sk)
    if mon is not None and monster_name(data, mon):
        return f'{monster_name(data, mon)}: monster skill'
    for off in (SK_SRVMIS[0], SK_CLTMIS[0]):
        m = _u16(r, off)
        if m not in NONE16:
            n = missile_name(data, m, depth=1)
            if n:
                return f'{n}: missile'
    m = _refs(data, 'missiles', (MI_SKILL,)).get(sk)
    if m is not None and missile_name(data, m, depth=1):
        return f'{missile_name(data, m, depth=1)}: missile'
    st = _refs(data, 'states', (ST_SKILL,)).get(sk)
    if st is not None:
        n = state_shown(data, st)
        if n:
            return f'{n}: state'
    # USED_SOURCES: summoner, prerequisite, own summon / states
    u = _refs(data, 'skills', SK_SUMSKILL).get(sk)
    if u is not None and skill_base(data, u):
        return f'{skill_base(data, u)}: summon skill'
    u = _refs(data, 'skills', SK_REQSKILL).get(sk)
    if u is not None and skill_base(data, u):
        return f'{skill_base(data, u)}: prereq'
    mid = _u16(r, SK_SUMMON)
    if mid not in NONE16 and monster_name(data, mid):
        return f'{monster_name(data, mid)}: summon'
    for off, role in ((SK_AURASTATE, 'aura'), (SK_PASSIVESTATE, 'passive'), (SK_AURATARGET, 'aura')):
        v = _u16(r, off)
        if v not in NONE16:
            n = state_shown(data, v)
            if n:
                return f'{n}: {role}'
    for off in SK_SRVMIS[1:] + SK_CLTMIS[1:]:
        m = _u16(r, off)
        if m not in NONE16 and missile_name(data, m, depth=1):
            return f'{missile_name(data, m, depth=1)}: missile'
    return None


def skill_fallback(data, sk):
    """Last resort from the row itself: class and server functions ('Druid skill, func 17/0')."""
    rs = rows(data, 'skills')
    if not 0 <= sk < len(rs):
        return None
    r = rs[sk]
    cl = r[SK_CLASS] if len(r) > SK_CLASS else 0xFF
    who = CLASS_NAMES[cl] if cl < len(CLASS_NAMES) else 'Monster'
    return f'{who} skill, func {_u16(r, SK_SRVST)}/{_u16(r, SK_SRVDO)}'


def state_shown(data, st):
    """A state's name without the 'used by' roles: buff icon text, vanilla key, else its own skill / overlay /
    missile (D2-Development-Kit NAME_SOURCES['states'])."""
    c = _cache(data)
    key = ('stshown', st)
    if key in c:
        return c[key]
    rs = rows(data, 'states')
    n = None
    if 0 <= st < len(rs):
        try:
            import mxl_statnames
            n = mxl_statnames._state_icon_names(data).get(st)
        except Exception:
            n = None
        n = n or vanilla_names(data, 'states').get(st)
        if not n:
            for off in (SK_AURASTATE, SK_AURATARGET, SK_PASSIVESTATE):
                sk = _refs(data, 'skills', (off,)).get(st)
                if sk is not None and skill_base(data, sk):
                    n = skill_base(data, sk)
                    break
        r = rs[st]
        if not n:
            sk = _u16(r, ST_SKILL)
            if sk not in NONE16:
                n = skill_base(data, sk)
        for off in (ST_OVERLAY1, ST_CASTOVERLAY):
            if not n:
                n = overlay_name(data, _u16(r, off))
        if not n:
            m = _u16(r, ST_MISSILE)
            if m not in NONE16:
                n = missile_name(data, m, depth=1)
    c[key] = n
    return n


def skill_any(data, sk):
    """A skill's display name or the editor's derived name for it (without the '(hidden #N)' tag); None when only
    the row-description fallback would name it."""
    n = skill_shown(data, sk)
    if n:
        return n
    try:
        import mxl_statnames
        n = mxl_statnames.hidden_skill_name(data, sk) or ''
    except Exception:
        n = skill_derived(data, sk) or ''
    n = re.sub(r'\s*\(hidden #\d+\)$', '', n)
    return n if n and n != skill_fallback(data, sk) and n != 'Unnamed skill' else None


def state_used(data, st):
    """'<user>: <role>' for a state nothing names (USED_SOURCES['states']), else a description of its row."""
    for off, role in ((SK_AURASTATE, 'aura'), (SK_PASSIVESTATE, 'passive'), (SK_AURATARGET, 'aura target')):
        sk = _refs(data, 'skills', (off,)).get(st)
        if sk is not None:
            n = skill_any(data, sk)
            if n:
                return f'{n}: {role}'
    sk = _refs(data, 'skills', SK_STATES).get(st)
    if sk is not None:
        n = skill_any(data, sk)
        if n:
            return f'{n}: state'
    for t in ('weapons', 'armor', 'misc'):
        i = _refs(data, t, IT_STATES).get(st)
        if i is not None:
            try:
                n = _cstr(rows(data, t)[i], 128, 4)
            except Exception:
                n = ''
            try:
                b = data.base(n)
                n = getattr(b, 'name', None) or n
            except Exception:
                pass
            return f'{n}: item'
    rs = rows(data, 'states')
    if not 0 <= st < len(rs):
        return None
    r = rs[st]
    sk = _u16(r, ST_SKILL)
    if sk not in NONE16:
        n = skill_any(data, sk)
        if n:
            return f'{n}: state'
    stat = _u16(r, ST_STAT)
    if stat not in NONE16 and _stat_name(data, stat):
        return f'{_stat_name(data, stat)}: state'
    return None


# states.bin flag bits (a little-endian bit field from +16; positions from the kit's layouts/mxl/states.json)
STATE_FLAGS = (('aura', 1), ('curse', 11), ('transform', 3), ('disguise', 16), ('active', 5), ('hide', 2),
               ('pgsv', 4), ('shatter', 31), ('udead', 33), ('exp', 30), ('life', 32), ('meleeonly', 38),
               ('restrict', 17), ('remhit', 6), ('curable', 12))


def state_fallback(data, st):
    """Last resort from the row itself: its flags ('aura, hide state'), else its group."""
    rs = rows(data, 'states')
    if not 0 <= st < len(rs):
        return None
    r = rs[st]
    bits = int.from_bytes(r[16:24], 'little') if len(r) >= 24 else 0
    flags = [n for n, b in STATE_FLAGS if bits >> b & 1][:3]
    if flags:
        return f"{', '.join(flags)} state"
    g = _u16(r, 30)
    return f'group {g} state' if g not in NONE16 else 'plain state'


def state_full(data, st):
    """Every state's name (for st a row of states.bin): shown, derived, used, else from its flags."""
    return state_shown(data, st) or state_used(data, st) or state_fallback(data, st)


def skill_full(data, sk):
    """Name of a skill without a display name of its own: derived, else from its row; None if no such row."""
    return skill_derived(data, sk) or skill_fallback(data, sk)


